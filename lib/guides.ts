export function buildKnowledgeGuide(term: KnowledgeTerm) {
  const depth = categoryDepth[term.category];
  return {
    mechanism: [
      { title: `先确认“${term.zh}”在描述什么`, text: `${term.summary} 理解它时先确定对象、时间范围和计量单位，避免把不同口径的数字放在一起比较。` },
      { title: '再理解它为什么重要', text: `${term.why} 关键不是背下名词，而是知道它会通过什么路径改变现金流、价格或风险。` },
      { title: '把关系放进真实场景', text: `${term.example} 把抽象概念换成具体金额、期限和参与者，通常更容易发现遗漏的假设。` },
      { title: '最后检查适用边界', text: depth.boundary },
    ],
    misconceptions: depth.misconceptions.map((item) => item.replaceAll('{term}', term.zh)),
    checklist: depth.checklist,
    observation: depth.observation,
  };
}

